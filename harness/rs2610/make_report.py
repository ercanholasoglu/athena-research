"""Assemble FINAL_RESEARCH_REPORT.md from the section templates in `report/` and render every {{key}} from outputs/facts.json.

    python -m rs2610.make_report      # run after make_facts; fails on unknown keys or on a missing / duplicated section

Each template holds one or more `## N. Title` sections; sections are ordered by N (1..30) whatever file they live in.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from rs2610.make_facts import OUT, render

ROOT = Path(__file__).resolve().parent
SECTIONS = range(1, 31)
HEAD = re.compile(r"^## (\d+)\. ", re.M)
DOCS = {"study_a/study-a-summary.md": [10, 12], "study_a/study-a-statistics.md": [11], "study_a/study-a-failures.md": [13],
        "study_b/study-b-summary.md": [17, 19], "study_b/study-b-statistics.md": [18], "study_b/study-b-failures.md": [20]}


def collect() -> dict[int, str]:
    found: dict[int, str] = {}
    for f in sorted((ROOT / "report").glob("*.md")):
        text = f.read_text()
        marks = list(HEAD.finditer(text))
        for i, m in enumerate(marks):
            n = int(m.group(1))
            if n in found:
                sys.exit(f"section {n} defined twice (second in {f.name})")
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            found[n] = text[m.start():end].rstrip() + "\n"
    missing = [n for n in SECTIONS if n not in found]
    if missing:
        sys.exit(f"missing sections: {missing}")
    return found


def main() -> None:
    facts = json.loads((OUT / "facts.json").read_text())
    sec = collect()
    head = ("# rs2610 — Reasoning topology (Study A) and semantic context (Study B) in AutoML decisions\n\n"
            "Final research report. Every number is rendered from `outputs/facts.json` (index: `outputs/facts-index.md`); "
            "generated by `python -m rs2610.make_report`, do not edit by hand.\n\n")
    toc = "".join(f"- {sec[n].splitlines()[0][3:]}\n" for n in SECTIONS)
    body = "\n".join(sec[n] for n in SECTIONS)
    (ROOT / "FINAL_RESEARCH_REPORT.md").write_text(render(head + "## Contents\n\n" + toc + "\n" + body, facts))
    print("wrote", ROOT / "FINAL_RESEARCH_REPORT.md", f"({len(sec)} sections)")
    for path, nums in DOCS.items():  # per-study extracts, rendered from the same sections
        (OUT / path).write_text(render("\n".join(sec[k] for k in nums), facts))
        print("wrote", OUT / path)


if __name__ == "__main__":
    main()
