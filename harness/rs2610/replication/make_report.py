"""Assemble FRONTIER_REPLICATION_REPORT.md from the section templates in `replication/report/` and render every {{key}}.

    python -m rs2610.replication.make_report    # run after make_facts; fails on unknown keys or a missing / duplicated section

Keys resolve from outputs/replication/facts-replication.json (r.*) and, for the few original-study numbers quoted in
the motivation, outputs/facts.json. Same section convention as rs2610.make_report.
"""
from __future__ import annotations

import json
import sys

from rs2610.make_facts import OUT, render
from rs2610.make_report import HEAD

from pathlib import Path

ROOT = Path(__file__).resolve().parent
SECTIONS = range(1, 12)
DEST = ROOT.parent / "FRONTIER_REPLICATION_REPORT.md"


def collect() -> dict[int, str]:
    found: dict[int, str] = {}
    for f in sorted((ROOT / "report").glob("*.md")):
        text = f.read_text()
        marks = list(HEAD.finditer(text))
        for i, m in enumerate(marks):
            n = int(m.group(1))
            if n in found:
                sys.exit(f"section {n} defined twice (second in {f.name})")
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            found[n] = text[m.start():end].rstrip() + "\n"
    missing = [n for n in SECTIONS if n not in found]
    if missing:
        sys.exit(f"missing sections: {missing}")
    return found


def main() -> None:
    facts = json.loads((OUT / "facts.json").read_text())
    rep = json.loads((OUT / "replication" / "facts-replication.json").read_text())
    assert not set(rep) & set(facts), "replication fact keys collide with original keys"
    facts.update(rep)
    sec = collect()
    head = ("# rs2610 — Frontier replication: Study A2 (reasoning topology) and Study B2 (semantic context)\n\n"
            "Every number is rendered from `outputs/replication/facts-replication.json` (index: "
            "`outputs/replication/facts-replication-index.md`); generated by `python -m rs2610.replication.make_report`, "
            "do not edit by hand. The original studies are reported in `FINAL_RESEARCH_REPORT.md` and are not modified.\n\n")
    toc = "".join(f"- {sec[n].splitlines()[0][3:]}\n" for n in SECTIONS)
    body = "\n".join(sec[n] for n in SECTIONS)
    # "p = {{k|p}}" renders "p = < 0.001" for tiny values; write it as "p < 0.001" like the original report
    DEST.write_text(render(head + "## Contents\n\n" + toc + "\n" + body, facts).replace("p = < 0.001", "p < 0.001"))
    print("wrote", DEST, f"({len(sec)} sections)")


if __name__ == "__main__":
    main()
