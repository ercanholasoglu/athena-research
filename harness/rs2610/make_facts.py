"""Flatten the canonical result tables into one keyed fact file, and render report templates from it.

    python -m rs2610.make_facts                    # outputs/facts.json (+ facts-index.md: key -> value -> source table/row)
    python -m rs2610.make_facts render T.md OUT.md # replace {{key}} / {{key|fmt}} in a template; fails on unknown keys

Every number in FINAL_RESEARCH_REPORT.md and in the blog articles is a {{key}} resolved here, so a number cannot be
typed by hand and every number traces to a row of a canonical CSV (the index records file and row selector per key).
Formats: |pct (0.123 -> 12.3%), |pp (signed percentage points), |2 / |3 (decimals), |int, |p (p-value), |ci (pct CI).
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "outputs"
A, Bd = OUT / "study_a", OUT / "study_b"


def _clean(v):
    if v is None:
        return None
    if isinstance(v, float) and math.isnan(v):
        return None
    if hasattr(v, "item"):
        v = v.item()
    return v


def _rows(path: Path, keys: list[str], prefix: str, facts: dict, index: dict) -> None:
    if not path.exists() or path.stat().st_size < 2:
        return
    df = pd.read_csv(path)
    for i, r in df.iterrows():
        k = ".".join([prefix] + [str(r[c]) for c in keys])
        for col in df.columns:
            if col in keys:
                continue
            v = _clean(r[col])
            if isinstance(v, (int, float, bool)) or v is None:
                facts[f"{k}.{col}"] = v
                index[f"{k}.{col}"] = f"{path.relative_to(ROOT)} row {i} ({', '.join(f'{c}={r[c]}' for c in keys)}) col {col}"


def build() -> dict:
    facts, index = {}, {}
    _rows(A / "study-a-results.csv", ["split", "mode"], "a", facts, index)
    _rows(A / "study-a-paired-tests.csv", ["split", "a", "b"], "a.paired", facts, index)
    _rows(A / "study-a-paired-regret.csv", ["split", "a", "b"], "a.regret", facts, index)
    _rows(A / "study-a-per-family.csv", ["split", "family", "mode"], "a.fam", facts, index)
    _rows(A / "study-a-paired-by-family.csv", ["split", "family", "a", "b"], "a.famtest", facts, index)
    _rows(A / "study-a-adversarial.csv", ["split", "variant", "mode"], "a.adv", facts, index)
    _rows(A / "study-a-topology-stats.csv", ["split", "mode"], "a.topo", facts, index)
    _rows(A / "study-a-confirmatory.csv", ["split", "hypothesis", "a", "b"], "a.h", facts, index)
    _rows(Bd / "study-b-results.csv", ["split", "variant", "condition"], "b", facts, index)
    _rows(Bd / "study-b-paired-tests.csv", ["split", "variant", "metric", "condition"], "b.paired", facts, index)
    _rows(Bd / "study-b-stability.csv", ["split", "variant", "condition"], "b.stab", facts, index)
    _rows(Bd / "study-b-confidence.csv", ["split", "condition"], "b.conf", facts, index)
    _rows(Bd / "study-b-sensitivity.csv", ["metric", "condition"], "b.sens", facts, index)
    _rows(Bd / "study-b-per-dataset.csv", ["split", "variant", "dataset_id", "condition"], "b.ds", facts, index)
    extra = OUT / "derived-facts.json"  # counts computed by analyze_extra.py (feature/candidate tallies, cross-study)
    if extra.exists():
        for k, v in json.loads(extra.read_text()).items():
            facts[k] = v["value"]
            index[k] = v["source"]
    return {"facts": facts, "index": index}


def fmt(v, mode: str | None) -> str:
    if v is None:
        return "UNKNOWN"
    if mode == "pct":
        return f"{100 * v:.1f}%"
    if mode == "pp":
        s = f"{100 * v:+.1f}".replace("-", "−")
        return "0.0" if s in ("+0.0", "−0.0") else s
    if mode == "p":
        return "< 0.001" if v < 0.001 else f"{v:.3f}"
    if mode == "int":
        return f"{int(round(v)):,}"
    if mode in ("0", "1", "2", "3", "4"):
        return f"{v:.{int(mode)}f}"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def render(template: str, facts: dict) -> str:
    missing = []

    def sub(m):
        key, _, mode = m.group(1).partition("|")
        if key not in facts:
            missing.append(key)
            return m.group(0)
        return fmt(facts[key], mode or None)
    out = re.sub(r"\{\{([^}]+)\}\}", sub, template)
    if missing:
        sys.exit("unknown fact keys: " + ", ".join(sorted(set(missing))))
    return out


def main() -> None:
    data = build()
    (OUT / "facts.json").write_text(json.dumps(data["facts"], indent=1, sort_keys=True))
    lines = ["# Fact index", "", "Key → canonical source. Generated by `python -m rs2610.make_facts`.", "", "| key | value | source |",
             "|---|---|---|"]
    lines += [f"| `{k}` | {fmt(data['facts'][k], None)} | {data['index'][k]} |" for k in sorted(data["facts"])]
    (OUT / "facts-index.md").write_text("\n".join(lines) + "\n")
    if len(sys.argv) > 1 and sys.argv[1] == "render":
        Path(sys.argv[3]).write_text(render(Path(sys.argv[2]).read_text(), data["facts"]))
        print("rendered", sys.argv[3])
    print(len(data["facts"]), "facts")


if __name__ == "__main__":
    main()
