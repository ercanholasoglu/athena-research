def page(did: str) -> str:
    s = SOURCES[did]
    return UCI_PAGE.format(id=s["uci"]) if "uci" in s else s["page"]


def download_url(did: str) -> str | None:
    s = SOURCES[did]
    if s["kind"] == "generated":
        return None
    return UCI_ZIP.format(id=s["uci"], slug=s["slug"]) if "uci" in s else s["url"]


def targets(did: str) -> list[Path]:
    s = SOURCES[did]
    if s["kind"] == "uci_archive":
        return [UCI / f"{s['uci']}.zip"]
    if s["kind"] == "extract":
        return [RAW / s["dir"] / m for m in s["members"]]
    if s["kind"] == "file":
        return [RAW / s["dest"]]
    return []


def label(p: Path) -> str:
    """Cache path relative to its root, as recorded in RECORDED_RAW_SHA256."""
    return f"UCI/{p.relative_to(UCI)}" if p.is_relative_to(UCI) else f"RAW/{p.relative_to(RAW)}"
